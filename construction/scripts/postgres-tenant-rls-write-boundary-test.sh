#!/usr/bin/env bash
set -euo pipefail

# Disposable PostgreSQL acceptance test for tenant RLS read/write boundaries.
# The fixture demonstrates PostgreSQL policy behavior, not Numou production wiring.
CONTAINER_NAME="numou-pg-tenant-rls-write-$$"
PORT="${NUMOU_TEST_PG_PORT:-55446}"
PASSWORD="numou_test_only"
cleanup() { docker rm -f "$CONTAINER_NAME" >/dev/null 2>&1 || true; }
trap cleanup EXIT

docker run -d --rm --name "$CONTAINER_NAME" \
  -e POSTGRES_PASSWORD="$PASSWORD" -e POSTGRES_DB=numou_test \
  -p "127.0.0.1:${PORT}:5432" postgres:16-alpine >/dev/null
for _ in $(seq 1 60); do
  if docker exec "$CONTAINER_NAME" pg_isready -U postgres -d numou_test >/dev/null 2>&1; then break; fi
  sleep 1
done
docker exec "$CONTAINER_NAME" pg_isready -U postgres -d numou_test >/dev/null

psql() { docker exec -i "$CONTAINER_NAME" psql -X -q -v ON_ERROR_STOP=1 -U postgres -d numou_test "$@"; }

psql <<'SQL'
CREATE ROLE numou_tenant_rls_write_test NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE TABLE tenant_rls_write_fixture (
  row_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id text NOT NULL,
  payload text NOT NULL
);
ALTER TABLE tenant_rls_write_fixture ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant_rls_write_fixture FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_rls_write_policy ON tenant_rls_write_fixture
  USING (tenant_id = current_setting('app.tenant_id', true))
  WITH CHECK (tenant_id = current_setting('app.tenant_id', true));
GRANT USAGE ON SCHEMA public TO numou_tenant_rls_write_test;
GRANT SELECT, INSERT, UPDATE ON tenant_rls_write_fixture TO numou_tenant_rls_write_test;
GRANT USAGE, SELECT ON SEQUENCE tenant_rls_write_fixture_row_id_seq TO numou_tenant_rls_write_test;
INSERT INTO tenant_rls_write_fixture (row_id, tenant_id, payload) VALUES
  (1, 'tenant-a', 'a-initial'), (2, 'tenant-b', 'b-initial');
SQL

# Missing tenant context fails closed for reads and writes.
NO_CONTEXT="$(psql -Atc "SET ROLE numou_tenant_rls_write_test; SELECT count(*) FROM tenant_rls_write_fixture")"
[[ "$NO_CONTEXT" == '0' ]] || { echo "FAIL: no-context query returned rows: $NO_CONTEXT" >&2; exit 1; }
if psql -c "SET ROLE numou_tenant_rls_write_test; INSERT INTO tenant_rls_write_fixture(row_id,tenant_id,payload) VALUES (10,'tenant-a','no-context')" >/dev/null 2>&1; then
  echo 'FAIL: insert without tenant context unexpectedly succeeded' >&2; exit 1
fi

# Tenant A can read/update its own row, but cannot write a row assigned to tenant B.
OWN_READ="$(psql -Atc "SET ROLE numou_tenant_rls_write_test; BEGIN; SELECT set_config('app.tenant_id','tenant-a',true); SELECT count(*) FROM tenant_rls_write_fixture; COMMIT")"
[[ "$OWN_READ" == *$'\n1' ]] || { echo "FAIL: tenant A expected one visible row: $OWN_READ" >&2; exit 1; }
if psql -c "SET ROLE numou_tenant_rls_write_test; BEGIN; SELECT set_config('app.tenant_id','tenant-a',true); INSERT INTO tenant_rls_write_fixture(row_id,tenant_id,payload) VALUES (11,'tenant-b','spoofed'); COMMIT" >/dev/null 2>&1; then
  echo 'FAIL: cross-tenant insert unexpectedly succeeded' >&2; exit 1
fi
if psql -c "SET ROLE numou_tenant_rls_write_test; BEGIN; SELECT set_config('app.tenant_id','tenant-a',true); UPDATE tenant_rls_write_fixture SET tenant_id='tenant-b' WHERE row_id=1; COMMIT" >/dev/null 2>&1; then
  echo 'FAIL: tenant ownership mutation unexpectedly succeeded' >&2; exit 1
fi

psql -c "SET ROLE numou_tenant_rls_write_test; BEGIN; SELECT set_config('app.tenant_id','tenant-a',true); UPDATE tenant_rls_write_fixture SET payload='a-updated' WHERE row_id=1; COMMIT" >/dev/null
STATE="$(psql -Atc "SELECT tenant_id || ':' || payload FROM tenant_rls_write_fixture WHERE row_id=1")"
[[ "$STATE" == 'tenant-a:a-updated' ]] || { echo "FAIL: own-tenant update missing or ownership changed: $STATE" >&2; exit 1; }

BYPASS="$(psql -Atc "SELECT rolsuper OR rolbypassrls FROM pg_roles WHERE rolname='numou_tenant_rls_write_test'")"
[[ "$BYPASS" == 'f' ]] || { echo 'FAIL: fixture role can bypass RLS' >&2; exit 1; }
echo 'PASS: missing tenant context fails closed for reads and writes.'
echo 'PASS: RLS WITH CHECK rejects cross-tenant inserts and tenant ownership changes.'
echo 'PASS: same-tenant updates work and the role cannot bypass RLS.'
echo 'NOTE: isolated fixture only; verify equivalent policies and grants against canonical Numou migrations and application roles.'
