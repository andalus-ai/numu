package tech.kayys.numou.workforce.domain.skill;

/**
 * Represents the proficiency level of a worker for a given skill.
 */
public enum ProficiencyLevel {

    /** Minimal exposure; learning the basics. */
    NOVICE,

    /** Has foundational knowledge; can work under guidance. */
    BEGINNER,

    /** Can work independently on standard tasks. */
    INTERMEDIATE,

    /** Deep knowledge; can mentor others. */
    ADVANCED,

    /** Recognised authority; drives innovation in the skill area. */
    EXPERT
}
