package tech.kayys.numou.identity.application.port;

import io.smallrye.mutiny.Uni;
import tech.kayys.numou.identity.application.dto.FederationAuthorizationRequest;
import tech.kayys.numou.identity.application.dto.FederationCallback;
import tech.kayys.numou.identity.domain.idp.IdentityProviderConfig;
import tech.kayys.numou.identity.domain.user.FederatedIdentity;

/**
 * SPI for an external identity provider (OIDC/OAuth2 today; SAML/LDAP plug in here).
 *
 * <p>Adapters own everything protocol-specific - discovery, PKCE, token exchange,
 * signature verification - and return the neutral {@link FederatedIdentity} the
 * application layer provisions from.
 */
public interface FederatedIdentityProviderPort {

    /**
     * Builds the URL the browser must be redirected to in order to start the login flow
     * (authorization endpoint + PKCE challenge + state + nonce).
     *
     * @param config  identity provider configuration
     * @param request state/nonce/PKCE challenge generated by the application layer
     * @return the absolute authorization URL
     */
    Uni<String> authorizationUrl(IdentityProviderConfig config, FederationAuthorizationRequest request);

    /**
     * Exchanges an authorization code for tokens, verifies the ID token against the
     * provider's JWKS and extracts the subject's claims.
     *
     * @param config   identity provider configuration
     * @param callback authorization code plus the PKCE verifier/nonce from {@link #authorizationUrl}
     * @return the assertions the provider made about the authenticated user
     */
    Uni<FederatedIdentity> exchangeCode(IdentityProviderConfig config, FederationCallback callback);
}
